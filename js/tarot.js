// Sharing templates
function buildShareText(card, category, orientation) {
  const oriText = orientation === 'up' ? 'ตั้ง' : 'กลับหัว';
  return `🎴 STARVIA ไพ่ทำนาย\n` +
    `หมวด: ${category.name} ${category.emoji}\n` +
    `ไพ่: ${card.name} (${card.thai}) ${card.emoji}\n` +
    `ทิศทาง: ${oriText}\n\n` +
    `✨ ${card.meaning[category.id][orientation]}\n\n` +
    `#STARVIA #ดูดวง #ไพ่ยิปซี #${category.name}`;
}

// Free tier: 1 card per day (stored in localStorage)
function getDailyCardCount() {
  const today = new Date().toISOString().split('T')[0];
  const stored = localStorage.getItem('starvia_tarot_count');
  if (!stored) return 0;
  const data = JSON.parse(stored);
  if (data.date !== today) return 0;
  return data.count;
}

function incrementDailyCardCount() {
  const today = new Date().toISOString().split('T')[0];
  const stored = localStorage.getItem('starvia_tarot_count');
  let data = stored ? JSON.parse(stored) : { date: today, count: 0 };
  if (data.date !== today) data = { date: today, count: 0 };
  data.count++;
  localStorage.setItem('starvia_tarot_count', JSON.stringify(data));
}

function canDrawFree() {
  return getDailyCardCount() < 1; // Free: 1 per day
}

function getRemainingFree() {
  return Math.max(0, 1 - getDailyCardCount());
}

